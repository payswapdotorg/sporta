/** A deterministic stepping clock (the repo's hermetic rig). */
function steppingClock(): () => number {
  let current = 1_999_999_999_000;
  return () => {
    current += 17;
    return current;
  };
}

function withCookie(token: string | null, path: string, init: RequestInit = {}): Request {
  return new Request(`http://sporta.test${path}`, {
    ...init,
    headers: {
      ...((init.headers as Record<string, string> | undefined) ?? {}),
      ...(token === null ? {} : { cookie: `${SPORTA_SESSION_COOKIE}=${token}` }),
    },
  });
}

async function bodyOf(response: Response): Promise<Record<string, unknown>> {
  return (await response.json()) as Record<string, unknown>;
}

function jsonPost(payload: unknown): RequestInit {
  return {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify(payload),
  };
}

/** Builds one real MP4 upload request (multipart, like a browser form). */
function uploadRequest(
  token: string | null,
  bytes: Uint8Array,
  operations: string[],
  options: { realitiesJson?: string; computeJson?: string; styleId?: string } = {},
): Request {
  const form = new FormData();
  form.append(
    "file",
    new File([bytes.slice().buffer as ArrayBuffer], "clip.mp4", { type: "video/mp4" }),
  );
  form.append("operations", JSON.stringify(operations));
  if (options.realitiesJson !== undefined) form.append("realities", options.realitiesJson);
  if (options.computeJson !== undefined) form.append("compute", options.computeJson);
  if (options.styleId !== undefined) form.append("styleId", options.styleId);
  return withCookie(token, "/api/create/upload-sessions", { method: "POST", body: form });
}

const FULL_OPERATIONS = ["analysis", "transformation", "derivativeGeneration", "storage"];

/** The card row shape the catalog/library answers carry. */
interface CardRow {
  renderId: string;
  rendererId: string;
  segmentCount: number;
  hasStoredOutputs: boolean;
}

/** One session card, as the API answers it (the fields this lane fixes). */
interface SessionCardAnswer {
  sessionId: string;
  label: string;
  status: string;
  createdAtIso: string;
  playback: { state: "authorized" | "denied"; reasonCode: "ok" | "rights-denied" };
  renders: CardRow[] | null;
  outputCount: number | null;
  realities:
    | {
        rendererId: string;
        renderId: string;
        state: "ready" | "no-stored-output" | "renderer-unavailable";
        segmentCount: number;
        hasStoredOutputs: boolean;
      }[]
    | null;
  realityCount: number | null;
  story: { source: "dev-seed"; storyKey: string; eventCount: number } | null;
}

