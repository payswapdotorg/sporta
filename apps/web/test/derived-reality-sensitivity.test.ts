describe("the J013 honest equivalence path — the same session rendered twice", () => {
  test(
    "byte-identical outputs carry the EXPLICIT equivalence explanation (or the honest regeneration note)",
    async () => {
      // The control: tactical on sessionA a SECOND time (the first ran in
      // the gate block above — both are real dispatches on the same SWM).
      await dispatchAndAwait(sessionA, "tactical.prototype");
      // Read BOTH renders' real output refs through the control plane
      // (the catalog is content-addressed — a byte-identical regeneration
      // dedupes to ONE artifact, which is itself the identity evidence).
      const { renders } = await server.control.listRenders(sessionA);
      const tacticalRenders = renders.filter(
        (render) => render.rendererId === "tactical.prototype",
      );
      expect(tacticalRenders.length).toBeGreaterThanOrEqual(2);
      const contentHashes: string[] = [];
      let swmProvenance: { snapshotVersion: number; lastEventSequence: number } | null = null;
      // The session's own artifact records, indexed by content hash (the
      // two render paths' ref schemes: `tactical-artifact://` and
      // `artifact://` — both content-addressed sha-256).
      const artifactsByHash = new Map(
        server.media
          .artifactsOfSession(sessionA)
          .filter((artifact) => artifact.reality === "tactical")
          .map((artifact) => [artifact.contentHash, artifact]),
      );
      for (const render of tacticalRenders) {
        const envelope = await server.control.getRender(sessionA, render.renderId);
        for (const segment of envelope.result.outputSegments) {
          const match = /^(?:tactical-)?artifact:\/\/([0-9a-f]{64})$/.exec(segment.artifactRef);
          if (match === null) continue;
          const contentHash = match[1]!;
          contentHashes.push(contentHash);
          const artifact = artifactsByHash.get(contentHash);
          if (artifact !== undefined) {
            const manifest = RenderArtifactManifest.parse(
              server.media.artifact(artifact.artifactId),
            );
            swmProvenance = manifest.swm;
          }
        }
      }
      expect(contentHashes.length).toBeGreaterThanOrEqual(2);
      const premise = swmMaterialDifference({
        left: swmInputsOf(sessionA),
        right: swmInputsOf(sessionA),
      });
      expect(premise.differs).toBe(false);
      const verdict = sensitivityVerdictOf({
        reality: "tactical",
        left: { contentHash: contentHashes[0]!, swm: swmProvenance },
        right: { contentHash: contentHashes[1]!, swm: swmProvenance },
        premise,
      });
      if (contentHashes[0] === contentHashes[1]) {
        // The byte-identical branch: the EXPLICIT explanation exists (the
        // same renderer over the same SWM produced the same content hash —
        // the store's content-addressed dedup is the identity evidence).
        expect(verdict.kind).toBe("equivalent");
        if (verdict.kind === "equivalent") {
          expect(verdict.explanation).toContain("byte-identical tactical artifacts");
          expect(verdict.explanation).toContain("deterministic");
        }
      } else {
        // The honest non-determinism branch: reported, never hidden.
        expect(verdict.kind).toBe("regenerated");
        if (verdict.kind === "regenerated") {
          expect(verdict.note).toContain("equivalent SWMs");
        }
      }
    },
    PER_TEST_TIMEOUT_MS,
  );
});

