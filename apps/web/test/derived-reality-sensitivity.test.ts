for (const { kind, rendererId, label } of REALITY_MATRIX) {
  describe(`the J013 gate — ${label} (${kind})`, () => {
    test(
      "meaningfully different SWMs → DIFFERENT real artifacts (the sensitivity direction)",
      async () => {
        // Both renders run through the REAL compute plane.
        await dispatchAndAwait(sessionA, rendererId);
        await dispatchAndAwait(sessionB, rendererId);
        const left = await latestArtifactOf(sessionA, kind);
        const right = await latestArtifactOf(sessionB, kind);
        // The premise, measured at the engines' own state.
        const premise = swmMaterialDifference({
          left: swmInputsOf(sessionA),
          right: swmInputsOf(sessionB),
        });
        expect(premise.differs).toBe(true);
        // The verdict: DIFFERENT content hashes (the renderer responded).
        const verdict = sensitivityVerdictOf({
          reality: kind as "tactical" | "three-d-game" | "anime-npr",
          left: left.record,
          right: right.record,
          premise,
        });
        expect(verdict.kind).toBe("sensitive");
        // The artifacts are REAL, materially different bytes.
        expect(left.descriptor.integrityHash).not.toBe(right.descriptor.integrityHash);
        expect(left.descriptor.byteSize).toBeGreaterThan(1024);
        expect(right.descriptor.byteSize).toBeGreaterThan(1024);
        // The frozen manifests record DIFFERENT SWM provenance (the
        // difference is documented at the manifest level, not inferred).
        expect(
          left.manifest.swm!.snapshotVersion === right.manifest.swm!.snapshotVersion &&
            left.manifest.swm!.lastEventSequence === right.manifest.swm!.lastEventSequence,
        ).toBe(false);
      },
      PER_TEST_TIMEOUT_MS,
    );
  });
}

