/** Dispatches ONE real render and polls the job to terminal success. */
async function dispatchAndAwait(sessionId: string, rendererId: string): Promise<string[]> {
  const dispatch = await renderRoute(
    withCookie(token, `/api/create/sessions/${sessionId}/renders`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ rendererId }),
    }),
    { params: Promise.resolve({ sessionId }) },
  );
  expect(dispatch.status).toBe(202);
  const dispatchBody = (await bodyOf(dispatch)) as { jobId: string };
  for (let attempt = 0; attempt < 600; attempt += 1) {
    const response = await jobRoute(
      withCookie(token, `/api/create/sessions/${sessionId}/jobs/${dispatchBody.jobId}`),
      { params: Promise.resolve({ sessionId, jobId: dispatchBody.jobId }) },
    );
    expect(response.status).toBe(200);
    const job = (await bodyOf(response)) as {
      state: string;
      completion?: { status: string; renderId: string };
    };
    if (job.completion !== undefined) {
      expect(job.completion.status).toBe("succeeded");
      return [dispatchBody.jobId, job.completion.renderId];
    }
    await Bun.sleep(25);
  }
  throw new Error(`the ${rendererId} render on ${sessionId} never reached terminal success`);
}

/** Dispatches ONE real render and polls to ANY terminal state (honest). */
async function dispatchExpecting(
  sessionId: string,
  rendererId: string,
): Promise<{
  terminal: boolean;
  completion?: { status: string; failure?: { errorClass: string; message: string } };
  failure?: { errorClass?: string };
}> {
  const dispatch = await renderRoute(
    withCookie(token, `/api/create/sessions/${sessionId}/renders`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ rendererId }),
    }),
    { params: Promise.resolve({ sessionId }) },
  );
  expect(dispatch.status).toBe(202);
  const dispatchBody = (await bodyOf(dispatch)) as { jobId: string };
  for (let attempt = 0; attempt < 600; attempt += 1) {
    const response = await jobRoute(
      withCookie(token, `/api/create/sessions/${sessionId}/jobs/${dispatchBody.jobId}`),
      { params: Promise.resolve({ sessionId, jobId: dispatchBody.jobId }) },
    );
    expect(response.status).toBe(200);
    const job = (await bodyOf(response)) as {
      state: string;
      completion?: { status: string; failure?: { errorClass: string; message: string } };
    };
    if (job.completion !== undefined) {
      return { terminal: true, completion: job.completion, failure: job.completion?.failure };
    }
    await Bun.sleep(25);
  }
  return { terminal: false };
}

/** Uploads one REAL clip and waits for the original artifact to exist. */
async function uploadClip(label: string, durationSeconds: number): Promise<string> {
  const clipPath = await generateTestMp4(join(scratch, `${label}.mp4`), {
    durationSeconds,
    withAudio: true,
    scene: "pitch-marked",
  });
  const bytes = new Uint8Array(await Bun.file(clipPath).arrayBuffer());
  const form = new FormData();
  form.append(
    "file",
    new File([bytes.slice().buffer as ArrayBuffer], `${label}.mp4`, { type: "video/mp4" }),
  );
  form.append(
    "operations",
    JSON.stringify(["analysis", "transformation", "derivativeGeneration", "storage"]),
  );
  form.append("label", `The J013 sensitivity clip (${label})`);
  const upload = await uploadSessionRoute(
    withCookie(token, "/api/create/upload-sessions", { method: "POST", body: form }),
  );
  expect(upload.status).toBe(201);
  const uploadBody = (await bodyOf(upload)) as {
    sessionId: string;
    source: { job: { jobId: string } | null };
  };
  expect(uploadBody.source.job).not.toBeNull();
  for (let attempt = 0; attempt < 600; attempt += 1) {
    const response = await mediaJobRoute(
      withCookie(token, `/api/media/jobs/${uploadBody.source.job!.jobId}`),
      { params: Promise.resolve({ jobId: uploadBody.source.job!.jobId }) },
    );
    const job = (await bodyOf(response)) as { terminal: boolean; state: string };
    if (job.terminal) {
      expect(job.state).toBe("succeeded");
      return uploadBody.sessionId;
    }
    await Bun.sleep(25);
  }
  throw new Error(`the ${label} upload never settled`);
}

