/** One session's SWM premise inputs (the engine's own snapshot + tail). */
function swmInputsOf(sessionId: string) {
  const engine = server.engines.get(sessionId)!;
  expect(engine).toBeDefined();
  const snapshot = engine.snapshot();
  const events = engine.eventsSince(0);
  return {
    snapshot: {
      sessionId: snapshot.sessionId,
      entities: snapshot.entities.map((entity) => ({
        entityId: entity.entityId,
        kind: entity.kind,
        version: entity.version,
        state: entity.state as unknown as Record<string, unknown>,
      })),
      watermark: snapshot.watermark,
    },
    events: events.map((entry) => ({
      sequence: entry.sequence,
      eventTimeMs: entry.event.eventTimeMs,
      eventTypeRef: entry.event.eventTypeRef,
    })),
  };
}

/** One session's LATEST artifact of one reality (the catalog's own data). */
async function latestArtifactOf(sessionId: string, kind: string) {
  const catalog = await buildWatchArtifactCatalog(server, sessionId);
  expect(catalog.playback.state).toBe("authorized");
  const entry = catalog.realities!.find((candidate) => candidate.kind === kind)!;
  expect(entry.availability).toBe("ready");
  expect(entry.artifacts.length).toBeGreaterThan(0);
  const descriptor = entry.artifacts[0]!;
  const manifest = RenderArtifactManifest.parse(server.media.artifact(descriptor.artifactId));
  const record: SensitivityArtifactRecord = {
    contentHash: manifest.contentHash,
    swm: manifest.swm,
    ...(manifest.sourceAssetId !== undefined ? { sourceContentHash: undefined } : {}),
  };
  return { descriptor, manifest, record };
}

