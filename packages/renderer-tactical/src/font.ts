/** Returns the glyph for `ch` (`?` shape for unknown characters). */
export function glyphOf(ch: string): Glyph {
  return GLYPHS[ch] ?? GLYPHS["?"] ?? [0x1f, 0x11, 0x15, 0x11, 0x1f, 0x11, 0x1f];
}

/**
 * Measures the pixel size of `text` at `scale` (integer >= 1). Width counts
 * one blank inter-character column per gap (6 columns per character total).
 */
export function measureText(text: string, scale = 1): { width: number; height: number } {
  return {
    width: Math.max(0, text.length * (GLYPH_WIDTH + 1) - 1) * scale,
    height: GLYPH_HEIGHT * scale,
  };
}
