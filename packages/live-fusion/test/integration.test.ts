function frameLine(input: {
  frame: number;
  timestamp: string | null;
  period: 1 | 2 | null;
  players: Array<{ x: number; y: number; id: number; detected: boolean | null }>;
  ball: { x: number | null; y: number | null; z: number | null; detected: boolean | null };
}): string {
  return JSON.stringify({
    frame: input.frame,
    timestamp: input.timestamp,
    period: input.period,
    ball_data: { x: input.ball.x, y: input.ball.y, z: input.ball.z, is_detected: input.ball.detected },
    possession: { player_id: null, group: null },
    image_corners_projection: {
      x_top_left: null,
      y_top_left: null,
      x_bottom_left: null,
      y_bottom_left: null,
      x_bottom_right: null,
      y_bottom_right: null,
      x_top_right: null,
      y_top_right: null,
    },
    player_data: input.players.map((player) => ({
      x: player.x,
      y: player.y,
      player_id: player.id,
      is_detected: player.detected,
    })),
  });
}

