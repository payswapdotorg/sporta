interface Composition {
  engine: WorldModelEngine;
  store: ObservationStore;
  fusion: LiveFusionEngine;
  reports: FusionReport[];
}

/** Drives N arrival streams through the ONE fusion composition, then finalizes. */
function driveComposition(
  arrivals: readonly LiveObservation[],
  options?: { policy?: Parameters<typeof createLiveFusionEngine>[0]["policy"]; endClockMs?: number },
): Composition {
  const engine = WorldModelEngine.create(SESSION_ID, {
    football: makeFootballState(),
    now: () => 0,
  });
  const store = new InMemoryObservationStore();
  const updater = createLiveSwmUpdater({ sessionId: SESSION_ID, engine, store });
  const temporal = createTemporalBufferEngine({ sessionId: SESSION_ID });
  const fusion = createLiveFusionEngine({
    sessionId: SESSION_ID,
    temporal,
    updater,
    ...(options?.policy !== undefined ? { policy: options.policy } : {}),
  });
  const reports: FusionReport[] = [];
  const sorted = [...arrivals].sort((a, b) => a.ingestTimeMs - b.ingestTimeMs);
  const lastIngestMs = sorted.length > 0 ? sorted[sorted.length - 1]!.ingestTimeMs : 0;
  const endClockMs = options?.endClockMs ?? lastIngestMs + 400;
  let next = 0;
  let clock = 0;
  while (clock <= endClockMs) {
    while (next < sorted.length && sorted[next]!.ingestTimeMs <= clock) {
      reports.push(fusion.admit(sorted[next]!));
      next += 1;
    }
    reports.push(fusion.tick(clock));
    clock += 100;
  }
  while (next < sorted.length) {
    reports.push(fusion.admit(sorted[next]!));
    next += 1;
  }
  reports.push(fusion.finalize());
  return { engine, store, fusion, reports };
}

/** Collects a pull-source's whole stream (planned ingest → next batch). */
function collectPulls(source: {
  plannedIngestTimeMs(): number | null;
  next(): LiveObservation | null;
}): LiveObservation[] {
  const batches: LiveObservation[] = [];
  for (;;) {
    if (source.plannedIngestTimeMs() === null) break;
    const batch = source.next();
    if (batch === null) break;
    batches.push(batch);
  }
  return batches;
}

/** Asserts the D8 replay equality over the bridged store (semantic state). */
function expectReplayEquality(composition: Composition): void {
  const replayEngine = WorldModelEngine.create(SESSION_ID, {
    football: makeFootballState(),
    now: () => 0,
  });
  runWorldFusion({ store: composition.store, engine: replayEngine, sessionId: SESSION_ID });
  const liveIds = [...composition.engine.entityIds].sort();
  const replayIds = [...replayEngine.entityIds].sort();
  expect(replayIds).toEqual(liveIds);
  for (const entityId of liveIds) {
    const liveEntity = composition.engine.entityAt(entityId)!;
    const replayEntity = replayEngine.entityAt(entityId)!;
    expect(replayEntity.kind).toBe(liveEntity.kind);
    expect(replayEntity.lastEventTimeMs).toBe(liveEntity.lastEventTimeMs);
    expect(JSON.stringify(replayEntity.state)).toBe(JSON.stringify(liveEntity.state));
  }
}

